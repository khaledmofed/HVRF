    function t(lang, key) {
        var dict = T[lang] || T.en;
        return dict[key] !== undefined ? dict[key] : (T.en[key] || key);
    }

    /* Update eco-wheel labels */
    function updateEcoLabels(lang) {
        var lblDiv = document.getElementById('ecoLbls');
        if (!lblDiv) return;
        var children = Array.from(lblDiv.children);
        var spanStyle = 'display:block;font-size:.82rem;font-weight:700;letter-spacing:.07em;color:rgba(255,255,255,.92);text-transform:uppercase;line-height:1.45;';

        /* node labels: children 0–6 */
        for (var i = 0; i < 7 && i < children.length - 1; i++) {
            var text = t(lang, 'ops.node-' + i);
            children[i].innerHTML = text.split('\n').map(function (p) {
                return '<span style="' + spanStyle + '">' + p + '</span>';
            }).join('');
        }

        /* center label: last child */
        var center = children[children.length - 1];
        if (center && center.dataset.ecoCenter !== undefined) {
            center.innerHTML =
                '<span style="display:block;font-size:.72rem;font-weight:700;letter-spacing:.14em;color:rgba(32,178,170,.92);text-transform:uppercase;line-height:1.8;">HVRF</span>' +
                '<span style="display:block;font-size:.62rem;font-weight:600;letter-spacing:.1em;color:rgba(255,255,255,.65);text-transform:uppercase;line-height:1.4;">' + t(lang, 'ops.center') + '</span>';
        }
    }

    /* Resolve the lang suffix for attribute lookups: zh-TW → zh-tw, ja → ja */
    function langSuffix(lang) {
        return lang.toLowerCase().replace('_', '-');
    }

    /* Resolve the data-db-{lang} attribute key: 'data-db-ja', 'data-db-zh-tw', etc. */
    function dbAttrName(lang) {
        return 'db-' + langSuffix(lang);
    }

    /* Main apply function */
    function applyLanguage(lang) {
        if (!T[lang]) lang = 'en';

        /* 1. textContent elements — DB attr takes priority over T lookup */
        document.querySelectorAll('[data-i18n]').forEach(function (el) {
            if (lang !== 'en') {
                var dbVal = el.getAttribute('data-' + dbAttrName(lang));
                if (dbVal !== null && dbVal.trim() !== '') {
                    el.textContent = dbVal;
                    return;
                }
            }
            el.textContent = t(lang, el.dataset.i18n);
        });

        /* 2. innerHTML elements (allow <br> etc.) */
        document.querySelectorAll('[data-i18n-html]').forEach(function (el) {
            el.innerHTML = t(lang, el.dataset.i18nHtml);
        });

        /* 3. placeholder attributes */
        document.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) {
            el.placeholder = t(lang, el.dataset.i18nPlaceholder);
        });

        /* 4. Eco wheel labels */
        updateEcoLabels(lang);

        /* 5. <html lang> attribute */
        var htmlEl = document.getElementById('htmlRoot');
        if (htmlEl) htmlEl.lang = lang;

        /* 6. Update lang button UI (all flag/code elements) */
        var meta = LANGS[lang] || LANGS.en;
        document.querySelectorAll('.lang-flag-icon').forEach(function (el) {
            el.className = 'lang-flag-icon fi fi-' + meta.iso;
        });
        document.querySelectorAll('.lang-code-text').forEach(function (el) { el.textContent = meta.code; });

        /* 7. Mark active option */
        document.querySelectorAll('.hvrf-lang-option').forEach(function (btn) {
            btn.classList.toggle('active', btn.dataset.lang === lang);
        });

        /* 8. Hero title (word-split) — DB attr takes priority, then T dict */
        var heroTitleEl = document.querySelector('.hero-title');
        if (heroTitleEl) {
            var sfx = langSuffix(lang);
            var titleVal = lang !== 'en' ? heroTitleEl.getAttribute('data-title-' + sfx) : '';
            if (!titleVal) titleVal = t(lang, 'hero.headline');
            if (!titleVal) titleVal = heroTitleEl.dataset.title || '';
            var words = titleVal.trim().split(/\s+/);
            heroTitleEl.innerHTML = words.map(function (w) {
                return '<span class="hw-wrap"><span class="hw-inner" style="opacity:1;transform:translateY(0);">' + w + '</span></span>';
            }).join(' ');
        }

        /* 9. Hero subtitle — DB attr takes priority, then T dict */
        var heroSubEl = document.querySelector('.hero-subtitle');
        if (heroSubEl) {
            var subVal = lang !== 'en' ? heroSubEl.getAttribute('data-subtitle-' + langSuffix(lang)) : '';
            if (!subVal) subVal = t(lang, 'hero.subheadline');
            if (!subVal) subVal = heroSubEl.dataset.subtitle || '';
            heroSubEl.textContent = subVal;
        }

        /* 10. Team role/bio — DB attr takes priority, else revert to data-original */
        document.querySelectorAll('.team-i18n-role, .team-i18n-bio').forEach(function (el) {
            var dbVal = lang !== 'en' ? el.getAttribute('data-' + dbAttrName(lang)) : '';
            el.textContent = (dbVal && dbVal.trim()) ? dbVal : (el.getAttribute('data-original') || '');
        });

        /* 10b. Initiator names — DB attr takes priority, else revert to data-original */
        document.querySelectorAll('.initiator-i18n-name').forEach(function (el) {
            var dbVal = lang !== 'en' ? el.getAttribute('data-' + dbAttrName(lang)) : '';
            el.textContent = (dbVal && dbVal.trim()) ? dbVal : (el.getAttribute('data-original') || '');
        });

        /* 11. Persist */
        try { localStorage.setItem(STORAGE_KEY, lang); } catch (e) {}
    }

    /* Initialise on DOM ready */
    function init() {
        var saved = 'en';
        try { saved = localStorage.getItem(STORAGE_KEY) || 'en'; } catch (e) {}
        if (!T[saved]) saved = 'en';

        /* Wire up lang option buttons */
        document.querySelectorAll('.hvrf-lang-option').forEach(function (btn) {
            btn.addEventListener('click', function () {
                applyLanguage(this.dataset.lang);
                /* Close Bootstrap dropdown */
                var dd = this.closest('.dropdown');
                if (dd) {
                    var toggle = dd.querySelector('[data-bs-toggle="dropdown"]');
                    if (toggle && window.bootstrap) {
                        var inst = bootstrap.Dropdown.getInstance(toggle);
                        if (inst) inst.hide();
                    }
                }
            });
        });

        /* Apply saved lang */
        applyLanguage(saved);
    }

    /* Expose for external use */
    window.HVRF_i18n = { apply: applyLanguage, t: t };

    /* Run after DOM is ready */
    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', init);
    } else {
        init();
    }
